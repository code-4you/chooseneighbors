  <section class="faq">
    <details>
      <summary>How many people do you need to start?</summary>
      <p>Fewer than you think. Most communities that exist began with two to five committed households. Three friends on one street is already a community — the structures can come later.</p>
    </details>
    <details>
      <summary>How much money does it take?</summary>
      <p>It depends on scale: a shared rental needs a bond; buying near each other needs ordinary deposits; a new-build village needs land finance and years. <a href="/belonging/homes.html">The ownership model</a> is designed so time and work can substitute for capital. Start at the scale your money allows now.</p>
    </details>
    <details>
      <summary>Do we need to buy land first?</summary>
      <p>No — people and agreements first, land after. Groups that buy land first often find the land choosing their members. When the group is real and the decision rules exist, the ground will follow.</p>
    </details>
    <details>
      <summary>What legal structure should we use?</summary>
      <p>Depends on country and scale — common shapes are a land trust holding the ground with homes individually owned, a cooperative, or an association alongside ordinary ownership. The principle: protect the community's purpose <em>and</em> each person's fair exit. <a href="/belonging/practical-backbone.html">The practical backbone</a> walks through it.</p>
    </details>
    <details>
      <summary>How long does it take?</summary>
      <p>Informal living-near-friends: one move. A shared house: weeks. A new-build community: 2–5 years. See <a href="/cohousing-vs-coliving.html">the model comparison</a> for time-to-start across all of them.</p>
    </details>
  </section>

