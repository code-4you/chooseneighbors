  <section class="step" id="why">
    <p class="kick">Step one</p>
    <h2>Why live near people you <em>chose</em></h2>
    <p>The housing market assigns your neighbours by accident, and it turns out the accident matters enormously. The <a href="/belonging/why-it-works-on-people.html">85-year Harvard Study of Adult Development</a> found the quality of our relationships predicts long-term health and happiness better than money, fame, or cholesterol. The US Surgeon General puts the toll of weak social connection on a par with smoking up to 15 cigarettes a day.</p>
    <p>But this isn't only about mood or a vague sense of belonging. Your body runs differently depending on who is nearby.</p>

    <aside class="evidence">
      <h3>The clenched state and the relaxed state</h3>
      <p class="sub">Two settings of the nervous system — and your street helps decide which one you live in.</p>
      <ul>
        <li><strong>The clench is vascular, not metaphorical.</strong> Threat activation constricts peripheral blood vessels and tenses muscle; safety does the opposite. Biofeedback clinics use hand temperature as their relaxation gauge precisely because calm means blood flowing back to the periphery.</li>
        <li><strong>Isolation is a chronic clench.</strong> Cacioppo's research found lonely people carry <a href="https://www.sciencedaily.com/releases/2006/03/060328081644.htm">higher peripheral vascular resistance and blood pressure even at rest</a> — up to ~30 points higher — <a href="https://pubmed.ncbi.nlm.nih.gov/28903579/">not only under stress</a>. The body of a person without trusted people nearby idles in low-grade vigilance, with inflammation and stress hormones downstream.</li>
        <li><strong>Trusted people turn the threat system down.</strong> <a href="https://www.frontiersin.org/journals/psychology/articles/10.3389/fpsyg.2020.00378/full">Social Baseline Theory</a> holds that the brain budgets its effort assuming trusted others are close; in the hand-holding experiments, threat-related brain activity dropped when holding a partner's hand. Alone is not the neutral setting — alone is the expensive setting.</li>
        <li><strong>Even imagined closeness registers.</strong> <a href="https://pubmed.ncbi.nlm.nih.gov/20967200/">Viewing a photo of a loved one measurably reduces induced pain</a>, and <a href="https://www.frontiersin.org/journals/human-neuroscience/articles/10.3389/fnhum.2013.00386/full">attachment figures act as safety signals</a> in ways controlled against mere distraction or familiarity.</li>
        <li><strong>Changing the environment changes the body.</strong> In the <a href="https://opportunityinsights.org/paper/newmto/">Moving to Opportunity</a> randomized trial, families given the chance to move to lower-poverty neighbourhoods showed less depression and anxiety, half the diabetes rate, and 40% less extreme obesity — a controlled experiment where a different street produced different physiology.</li>
      </ul>
    </aside>

    <p class="deeper"><b>Go deeper:</b> <a href="/belonging/why-it-works-on-people.html">Why it works on people</a> — the full evidence essay.</p>
  </section>

  <section class="step" id="shape">
    <p class="kick">Step two</p>
    <h2>Pick your <em>shape</em></h2>
    <p>Before people, before land, before money: decide how much sharing you actually want — because the models differ far more than the words suggest. <strong>Cohousing</strong> gives each household a full private home with shared spaces between. <strong>Coliving</strong> shares one big home. <strong>Ecovillages and communes</strong> share values, land, sometimes income. <strong>Living near friends informally</strong> shares nothing but a street — and is wildly underrated.</p>
    <p>The honest test: do you want your own kitchen, and will you still want it in ten years? Mismatched expectations about sharing are the most common reason communities dissolve.</p>
    <p class="deeper"><b>Go deeper:</b> <a href="/cohousing-vs-coliving.html">Cohousing vs coliving — the full comparison</a>, with a side-by-side table of privacy, cost, ownership, and time-to-start.</p>
  </section>

  <section class="step" id="people">
    <p class="kick">Step three</p>
    <h2>Gather your <em>people</em></h2>
    <p>Every community that exists began the same way: two to five people who wouldn't drop the idea — the "burning souls." You don't need twenty households; you need a core who will still be having this conversation in six months. Start there.</p>
    <p>Make the implicit explicit early. Who's in if it's a rented house? Who's only in for ownership? Who needs to stay near a job, a school, an ageing parent? A community that begins by hearing each person's real constraints outlives one that begins with a shared fantasy.</p>
    <p>Then widen deliberately: friends-of-friends beat strangers, because trust already has somewhere to stand. New members chosen by people who know them keep the web of relationships continuous — <a href="/belonging/choose-your-neighbours.html">choosing neighbours by application</a> covers how this works at village scale without becoming a clique.</p>
    <p class="deeper"><b>The tool:</b> <a href="/groups">create a group on Choose Neighbors</a> — a place for your core group to plan a street, a building, or a whole community together.</p>
  </section>

  <section class="step" id="scale">
    <p class="kick">Step four</p>
    <h2>Pick your <em>scale</em> — and start smaller than your dream</h2>
    <p>The dream might be a village. The start is almost never a village. The scales, smallest first:</p>
    <div class="tablewrap"><table>
      <thead><tr><th>Scale</th><th>What it looks like</th><th>Time to start</th></tr></thead>
      <tbody>
        <tr><th>A shared house</th><td>Rent a big place together — the cheapest test of shared daily life</td><td>Weeks</td></tr>
        <tr><th>A street</th><td>Buy or rent within walking distance; share meals, tools, childcare</td><td>Months, one move at a time</td></tr>
        <tr><th>A building</th><td>A small apartment block or subdivided property, owned or leased together</td><td>6–18 months</td></tr>
        <tr><th>A village</th><td>New-built or converted; land held in trust, homes owned at cost</td><td>2–5 years</td></tr>
      </tbody>
    </table></div>
    <p>Each scale is complete in itself and rehearsal for the next. A street that eats together already delivers most of the physiology in step one.</p>
  </section>

  <section class="step" id="money">
    <p class="kick">Step five</p>
    <h2>Homes &amp; <em>money</em></h2>
    <p>Money is where community ideals meet their first real test. The model we think works best: <strong>land held in trust, homes owned from day one</strong> at what they cost to create — not what a market will bear — with resale capped at cost plus inflation, so nobody profits merely by holding a home someone else needs. Your time can be part of your deposit: building is paid work anyone can learn.</p>
    <p>Whatever model you choose, get the legal skeleton in place before the first dollar moves: who owns what, how someone leaves, what happens on death or default. Communities rarely die of bad intentions; they die of unwritten agreements.</p>
    <p class="deeper"><b>Go deeper:</b> <a href="/belonging/homes.html">Homes you own, never rent</a> — the ownership model in full · <a href="/belonging/practical-backbone.html">The practical backbone</a> — legal structure, bills, and a resilient local economy.</p>
  </section>

  <section class="step" id="decide">
    <p class="kick">Step six</p>
    <h2>Decide <em>together</em> without deadlock</h2>
    <p>Governance sounds like the boring part. It is actually the survival part: a community lives or dies on how it handles its own friction. You need three things agreed while everyone still likes each other — how ordinary decisions get made (consent-based methods beat unanimous consensus), how conflict is resolved without exile, and money everyone can see.</p>
    <p>Design is governance too. The people who live somewhere should shape it — organisers stepping forward, an open index of ideas, good ideas getting backing — rather than inheriting someone else's plan.</p>
    <p class="deeper"><b>Go deeper:</b> <a href="/belonging/governing-ourselves.html">Governing ourselves</a> — conflict, rules, and transparent money · <a href="/belonging/you-design-it.html">You design it</a> — participatory design that works.</p>
  </section>

  <section class="step" id="life">
    <p class="kick">Step seven</p>
    <h2>Share the work <em>and the days</em></h2>
    <p>After the founding excitement comes ordinary life — which is the point. Two questions decide whether ordinary life together works. First, contribution: if nobody is forced to work, who cooks, who fixes, who cares? The answer is contribution without coercion — visible needs, chosen roles, and care treated as infrastructure rather than a favour. Second, texture: there should always be something happening you can join without an invitation.</p>
    <p class="deeper"><b>Go deeper:</b> <a href="/belonging/pulling-our-weight.html">Pulling our weight</a> — contribution and care · <a href="/belonging/things-to-do.html">Always something to do</a> — the daily-life design.</p>
  </section>

  <section class="step" id="risks">
    <p class="kick">Step eight</p>
    <h2>Know the risks <em>honestly</em></h2>
    <p>Every feature that makes chosen community powerful carries a shadow. Choosing neighbours can slide into discriminating. A tight community can become hard to leave. An app that knows who's around can watch instead of protect. Taking these seriously from the start — open selection criteria, guaranteed exit terms, privacy by design — is what separates a healthy community from the cautionary tales.</p>
    <p class="deeper"><b>Go deeper:</b> <a href="/belonging/keeping-people-safe.html">Keeping people safe</a> — the risks and the safeguards, one by one.</p>
  </section>

  <section class="step" id="last">
    <p class="kick">Step nine</p>
    <h2>Build it <em>to last</em></h2>
    <p>Most intentional communities fail — not from conflict, usually, but from quieter causes: ageing out, growing past the size where people know each other, hardening into a creed, or breaking the first time a member dies or defaults. The remedies are structural: build for families and elders, grow as small connected villages rather than one big town, stay creedless, and write the hard scenarios into the agreements before they happen.</p>
    <p class="deeper"><b>Go deeper:</b> <a href="/belonging/what-makes-it-last.html">What makes it last</a> — the short version · <a href="/belonging/built-to-last.html">Built to last</a> — the four quiet killers and their fixes.</p>
  </section>

